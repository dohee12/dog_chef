-- 멍슐랭: 계획서(docs/plan-safety-v12.md 8장)가 쓰기로 했지만 아직 없는 테이블 3개
--   intake_logs : 먹었어요 계산기 기록 (src/v12/logic/calc.ts saveIntake / HistoryItem)
--   reviews     : 레시피 리뷰 (Supabase_RLS_설정.sql 4장 정책, backend/src/reviews/review.entity.ts 칸)
--   food_cache  : 식약처 영양 DB 응답 캐시 (Edge Function 이 service_role 로 저장)
-- recipes·pets·likes 테이블과 그 정책은 건드리지 않는다.

-- =========================================================
-- 1. intake_logs
-- =========================================================
create table if not exists public.intake_logs (
  id              bigint generated by default as identity primary key,
  pet_id          bigint not null references public.pets(id) on delete cascade,
  user_id         uuid   not null default auth.uid() references auth.users(id) on delete cascade,
  device_id       text   not null,
  food            text   not null check (char_length(food) between 1 and 50),   -- calc.food (예: chocolate, grapes-raisins)
  food_sub        text,                                                          -- 종류 (calc.sub 의 이름, 예: 다크 / 마늘)
  cacao_pct       numeric check (cacao_pct is null or (cacao_pct > 0 and cacao_pct <= 100)),
  amount          numeric check (amount is null or amount >= 0),                 -- null = 양 모름
  amount_unit     text check (amount_unit is null or char_length(amount_unit) between 1 and 10), -- g / 개 / 알 / 쪽
  amount_unknown  boolean not null default false,
  what_text       text   not null check (char_length(what_text) between 1 and 200), -- 화면에 보인 "무엇·얼마나" 문장
  calc_weight     numeric not null check (calc_weight >= 0.5 and calc_weight <= 100), -- 계산에 쓴 몸무게(kg)
  weight_temp     boolean not null default false,                                -- 계산기에서 임시로 바꾼 몸무게인지
  calc_value      text,                                                          -- 계산값 문장 (r.num, 예: 몸무게 1kg당 약 ○mg)
  level           smallint not null check (level in (-2, 1, 2, 3)),              -- -2 계산 못 함, 1 전화, 2 병원, 3 응급
  ate_at          timestamptz not null,                                          -- 먹은 시각
  created_at      timestamptz not null default now(),
  constraint intake_logs_amount_unit_chk check (amount is null or amount_unit is not null),
  -- 같은 기록이 두 번 들어가지 않게 (saveIntake 의 savedKeys 와 같은 기준)
  constraint intake_logs_no_dup unique nulls not distinct
    (pet_id, food, food_sub, cacao_pct, amount, amount_unit, amount_unknown, calc_weight, ate_at)
);

create index if not exists intake_logs_pet_id_idx  on public.intake_logs (pet_id);
create index if not exists intake_logs_user_id_idx on public.intake_logs (user_id);
create index if not exists intake_logs_ate_at_idx  on public.intake_logs (pet_id, ate_at desc);

alter table public.intake_logs enable row level security;

-- pets·likes 와 같은 패턴: 로그인한 본인 것만
drop policy if exists "Users manage own intake logs" on public.intake_logs;
create policy "Users manage own intake logs"
  on public.intake_logs for all
  to authenticated
  using ((select auth.uid()) = user_id)
  with check (
    (select auth.uid()) = user_id
    and exists (select 1 from public.pets p where p.id = pet_id and p.user_id = (select auth.uid()))
  );

-- =========================================================
-- 2. reviews
-- =========================================================
create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  recipe_id   bigint not null references public.recipes(id) on delete cascade,
  user_id     uuid   not null default auth.uid() references auth.users(id) on delete cascade,
  device_id   text   not null,
  pet_id      bigint references public.pets(id) on delete set null,          -- 어느 아이에게 먹였는지 (선택)
  rating      smallint not null check (rating between 1 and 5),
  comment     text   not null default '' check (char_length(comment) <= 1000),
  images      jsonb  not null default '[]'::jsonb check (jsonb_typeof(images) = 'array'),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  constraint reviews_one_per_user unique (user_id, recipe_id)
);

create index if not exists reviews_recipe_id_idx on public.reviews (recipe_id);
create index if not exists reviews_pet_id_idx    on public.reviews (pet_id);

create or replace function public.reviews_touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists reviews_touch_updated_at on public.reviews;
create trigger reviews_touch_updated_at
  before update on public.reviews
  for each row execute function public.reviews_touch_updated_at();

alter table public.reviews enable row level security;

-- Supabase_RLS_설정.sql 4장과 같은 내용 (auth.uid() 는 (select auth.uid()) 로)
drop policy if exists "Anyone can view reviews" on public.reviews;
create policy "Anyone can view reviews"
  on public.reviews for select
  to anon, authenticated
  using (true);

drop policy if exists "Authenticated users can create reviews" on public.reviews;
create policy "Authenticated users can create reviews"
  on public.reviews for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can update own reviews" on public.reviews;
create policy "Users can update own reviews"
  on public.reviews for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can delete own reviews" on public.reviews;
create policy "Users can delete own reviews"
  on public.reviews for delete
  to authenticated
  using ((select auth.uid()) = user_id);

-- =========================================================
-- 3. food_cache
-- =========================================================
create table if not exists public.food_cache (
  food_code   text primary key check (char_length(food_code) between 1 and 50), -- 식약처 식품코드
  food_name   text not null check (char_length(food_name) between 1 and 200),
  source      text not null default 'mfds',                                    -- 어느 API 에서 왔는지
  raw         jsonb not null,                                                  -- API 원본 응답 (한 식품)
  fetched_at  timestamptz not null default now()
);

create index if not exists food_cache_food_name_idx on public.food_cache (food_name);

alter table public.food_cache enable row level security;

-- 읽기는 누구나, 쓰기 정책은 두지 않는다 → service_role(Edge Function)만 쓸 수 있다 (RLS 우회)
drop policy if exists "Anyone can read food cache" on public.food_cache;
create policy "Anyone can read food cache"
  on public.food_cache for select
  to anon, authenticated
  using (true);

revoke insert, update, delete, truncate on public.food_cache from anon, authenticated;
